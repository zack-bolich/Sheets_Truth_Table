// Produces a clasp-pushable directory (default: build/):
//
//   core.js         esbuild IIFE bundle of apps/sheets/src/adapter.ts and the
//                   core library, exposed as the global `SheetsLogic`
//   functions.js    apps/sheets/src/functions.ts transpiled but NOT bundled,
//                   so the @customfunction declarations stay global
//   appsscript.json the Apps Script manifest
//
// Usage: node scripts/build.mjs [--outdir <dir>]
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { build } from 'esbuild';
import ts from 'typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const app = join(root, 'apps/sheets');
const { values } = parseArgs({ options: { outdir: { type: 'string', default: 'build' } } });
const outdir = resolve(root, values.outdir);
const banner =
  '// Generated by scripts/build.mjs from sheets-logic. Do not edit: change the source in the\n' +
  '// repo and run `npm run push`. Edits made in the Apps Script editor are overwritten.\n';

await rm(outdir, { recursive: true, force: true });
await mkdir(outdir, { recursive: true });

await build({
  entryPoints: [join(app, 'src/adapter.ts')],
  outfile: join(outdir, 'core.js'),
  bundle: true,
  format: 'iife',
  globalName: 'SheetsLogic',
  platform: 'neutral',
  mainFields: ['main'],
  target: 'es2020',
  charset: 'utf8',
  legalComments: 'none',
  banner: { js: banner.trimEnd() },
  logLevel: 'warning',
});

// esbuild drops ordinary comments, which would lose the JSDoc that Sheets reads
// for autocomplete, so the stubs go through the TypeScript transpiler instead.
const functionsSource = await readFile(join(app, 'src/functions.ts'), 'utf8');
const { outputText } = ts.transpileModule(functionsSource, {
  compilerOptions: { target: ts.ScriptTarget.ES2020, removeComments: false },
  fileName: 'functions.ts',
  reportDiagnostics: false,
});
checkFunctions(outputText);
await writeFile(join(outdir, 'functions.js'), banner + outputText);

await copyFile(join(app, 'appsscript.json'), join(outdir, 'appsscript.json'));

console.log(`Built ${values.outdir}/: core.js, functions.js, appsscript.json`);

/** Fails the build if the stubs would not load as plain global functions. */
function checkFunctions(js) {
  if (/^\s*(import|export)\b/m.test(js) || /\brequire\(/.test(js)) {
    throw new Error('functions.ts must not import or export anything');
  }
  const declared = [...js.matchAll(/^function ([A-Z][A-Z0-9_]*)\(/gm)].length;
  const tagged = [...js.matchAll(/^\s*\* @customfunction$/gm)].length;
  if (declared === 0 || declared !== tagged) {
    throw new Error(
      `functions.ts declares ${declared} top-level custom functions but has ${tagged} @customfunction tags`,
    );
  }
}
